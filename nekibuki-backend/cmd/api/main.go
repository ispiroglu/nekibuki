package main

import (
	"context"
	"log/slog"
	"net/http"
	"os"
	"os/signal"
	"syscall"
	"time"

	"nekibuki-backend/internal/config"
	"nekibuki-backend/internal/database"
	"nekibuki-backend/internal/handlers"
	"nekibuki-backend/internal/middleware"
	"nekibuki-backend/internal/services/gemini"
	"nekibuki-backend/internal/services/recognition"
	"nekibuki-backend/internal/storage"

	_ "nekibuki-backend/docs" // This will be generated by swag

	httpSwagger "github.com/swaggo/http-swagger"
)

// @title Nekibuki API
// @version 1.0.0
// @description This is the Nekibuki backend API server for tourist attraction recognition
// @termsOfService http://swagger.io/terms/

// @contact.name API Support
// @contact.url http://www.swagger.io/support
// @contact.email support@swagger.io

// @license.name MIT
// @license.url https://opensource.org/licenses/MIT

// @host localhost:8080
// @BasePath /
// @schemes http https

// @tag.name Health
// @tag.description Health check operations

// @tag.name Recognition
// @tag.description Photo recognition and tourist attraction identification

func main() {
	// Load configuration
	cfg, err := config.Load()
	if err != nil {
		slog.Error("Failed to load configuration", "error", err)
		os.Exit(1)
	}

	// Configure structured logging
	setupLogging(cfg)

	// Connect to database
	db, err := database.Connect(cfg)
	if err != nil {
		slog.Error("Failed to connect to database", "error", err)
		os.Exit(1)
	}
	defer db.Close()

	// Initialize Gemini service
	geminiService, err := gemini.NewGeminiService(context.Background(), cfg.Gemini.APIKey)
	if err != nil {
		slog.Error("Failed to initialize Gemini service", "error", err)
		os.Exit(1)
	}

	// Initialize image storage
	imageStorage, err := storage.NewImageStorage(cfg.Storage.LocalPath)
	if err != nil {
		slog.Error("Failed to initialize image storage", "error", err)
		os.Exit(1)
	}

	// Initialize recognition service
	recognitionService := recognition.NewRecognitionService(db.Queries, geminiService, imageStorage)

	// Initialize handlers
	healthHandler := handlers.NewHealthHandler(db)
	recognitionHandler := handlers.NewRecognitionHandler(recognitionService)

	// Create HTTP mux
	mux := http.NewServeMux()

	// Register API routes
	mux.HandleFunc("GET /api/health", healthHandler.HealthCheck)

	// Recognition endpoints
	mux.HandleFunc("POST /api/recognition/upload", recognitionHandler.UploadPhoto)
	mux.HandleFunc("GET /api/recognition/result/{session_id}", recognitionHandler.GetResult)
	mux.HandleFunc("GET /api/recognition/sessions", recognitionHandler.GetRecentSessions)

	// Register Swagger routes
	mux.HandleFunc("GET /swagger/", httpSwagger.WrapHandler)

	// Create middleware chain
	handler := middleware.Recovery(
		middleware.Logging(
			middleware.CORS(
				middleware.GeneralLimiter.RateLimit(mux),
			),
		),
	)

	// Create HTTP server
	server := &http.Server{
		Addr:         cfg.ServerAddress(),
		Handler:      handler,
		ReadTimeout:  cfg.Server.ReadTimeout,
		WriteTimeout: cfg.Server.WriteTimeout,
		IdleTimeout:  cfg.Server.IdleTimeout,
	}

	// Start server in a goroutine
	go func() {
		slog.Info("Starting Nekibuki API server",
			"address", cfg.ServerAddress(),
			"swagger_url", "http://"+cfg.ServerAddress()+"/swagger/")

		slog.Info("Recognition endpoints available",
			"upload", "POST /api/recognition/upload",
			"result", "GET /api/recognition/result/{session_id}",
			"sessions", "GET /api/recognition/sessions")

		if err := server.ListenAndServe(); err != nil && err != http.ErrServerClosed {
			slog.Error("Server failed to start", "error", err)
			os.Exit(1)
		}
	}()

	// Wait for interrupt signal to gracefully shutdown the server
	quit := make(chan os.Signal, 1)
	signal.Notify(quit, syscall.SIGINT, syscall.SIGTERM)
	<-quit
	slog.Info("Shutting down server...")

	// Graceful shutdown
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	if err := server.Shutdown(ctx); err != nil {
		slog.Error("Server forced to shutdown", "error", err)
		os.Exit(1)
	}

	slog.Info("Server shutdown complete")
}

// setupLogging configures structured logging based on configuration
func setupLogging(cfg *config.Config) {
	var level slog.Level

	switch cfg.Development.LogLevel {
	case "debug":
		level = slog.LevelDebug
	case "info":
		level = slog.LevelInfo
	case "warn":
		level = slog.LevelWarn
	case "error":
		level = slog.LevelError
	default:
		level = slog.LevelInfo
	}

	var handler slog.Handler
	if cfg.Development.Debug {
		// Human-readable format for development
		handler = slog.NewTextHandler(os.Stdout, &slog.HandlerOptions{
			Level:     level,
			AddSource: true,
		})
	} else {
		// JSON format for production
		handler = slog.NewJSONHandler(os.Stdout, &slog.HandlerOptions{
			Level:     level,
			AddSource: false,
		})
	}

	logger := slog.New(handler)
	slog.SetDefault(logger)
}
